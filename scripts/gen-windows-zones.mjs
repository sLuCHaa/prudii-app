// Regenerates src-tauri/src/calendar/windows_zones.rs from CLDR's windowsZones.xml.
// Run from the repo root: node scripts/gen-windows-zones.mjs
import { writeFileSync } from "node:fs";

const CLDR_TAG = "release-46";
const url = `https://raw.githubusercontent.com/unicode-org/cldr/${CLDR_TAG}/common/supplemental/windowsZones.xml`;
const res = await fetch(url);
if (!res.ok) throw new Error(`CLDR download failed: ${res.status}`);
const xml = await res.text();

// territory="001" is CLDR's canonical IANA zone for each Windows zone.
const rows = [...xml.matchAll(/<mapZone other="([^"]+)" territory="001" type="([^"]+)"\s*\/>/g)]
  .map(([, windows, iana]) => [windows, iana.split(" ")[0]])
  .sort((a, b) => a[0].localeCompare(b[0]));
if (rows.length < 100) throw new Error(`unexpectedly few zones: ${rows.length}`);

const body = rows.map(([w, i]) => `    ("${w}", "${i}"),`).join("\n");
writeFileSync(
  "src-tauri/src/calendar/windows_zones.rs",
  `// Generated by scripts/gen-windows-zones.mjs from CLDR ${CLDR_TAG} windowsZones.xml. Do not edit.\n` +
    `pub const WINDOWS_TO_IANA: &[(&str, &str)] = &[\n${body}\n];\n`,
);
console.log(`${rows.length} zones written`);
